// Preserve legacy English wording while routing it to the complete six-language rows.
import ts from 'typescript';
import vm from 'node:vm';
import {readFileSync,writeFileSync} from 'node:fs';
import {WEB_FILES} from './ios-release.mjs';
const ctx=vm.createContext({console});ctx.window=ctx;
for(const file of ['v2-i18n.js','game-locale.js','game-locale-data.js','game-locale-intro.js','game-locale-ranked.js','game-locale-extra.js'])vm.runInContext(readFileSync(file,'utf8'),ctx);
ctx.SpaceTowerLocale.register(ctx.V2_I18N);
const aliases=new Map();
function literal(n){
 if(ts.isStringLiteralLike(n))return {text:n.text,parameters:[]};
 if(ts.isTemplateExpression(n))return {text:n.head.text+n.templateSpans.map((s,i)=>'{'+i+'}'+s.literal.text).join(''),parameters:n.templateSpans.map(s=>s.expression.getText())};
}
for(const file of WEB_FILES.filter(f=>(f.endsWith('.js')&&!f.startsWith('game-locale'))||f==='index.html')){
 let code=readFileSync(file,'utf8');if(file.endsWith('.html'))code=[...code.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)].map(m=>m[1]).join('\n');
 const ast=ts.createSourceFile(file,code,ts.ScriptTarget.Latest,true,ts.ScriptKind.JS);
 function visit(n){
  if(ts.isConditionalExpression(n)&&/\b(zh|isZh|currentLanguage)\b/.test(n.condition.getText())){
   const a=literal(n.whenTrue),b=literal(n.whenFalse),row=a&&ctx.SpaceTowerLocale.entries.get(a.text.trim().replace(/\s+/g,' '));
   if(row&&b&&b.text!=='Player ID'&&!/<[a-z]|[\u3400-\u9fff]/i.test(b.text)&&JSON.stringify(a.parameters)===JSON.stringify(b.parameters)&&b.text!==row.en)aliases.set(b.text,[row.en,row.ja,row.ko,row.ru,row.es]);
  }
  ts.forEachChild(n,visit);
 }visit(ast);
}
writeFileSync('game-locale-aliases.js','/* Generated by tools/build-locale-aliases.mjs from legacy bilingual labels. */\n(()=>{for(const [source,values] of '+JSON.stringify([...aliases],null,2)+')SpaceTowerLocale.add(source,values);})();\n');
console.log(`${aliases.size} legacy English labels mapped to six languages.`);
